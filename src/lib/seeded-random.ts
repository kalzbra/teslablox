/**
 * Deterministic "looks shuffled" helpers. Static export prerenders client components to HTML at
 * build time, then hydrates them in the browser — if a render uses Math.random(), the server
 * and client renders produce different output and React throws a hydration-mismatch error. These
 * are pure functions of a seed instead, so the same seed always produces the same shuffle in
 * both environments.
 */
function mulberry32(seed: number) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function seededShuffle<T>(items: T[], seed: number): T[] {
  const rand = mulberry32(seed);
  const result = [...items];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
